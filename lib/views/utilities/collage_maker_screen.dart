    if (_selectedMonth != 'all') {
      return CollageDecor.memory(
        occasionLabel: 'Kỷ niệm ${_displayMonthLabel(_selectedMonth)}',
        message:
            'Tháng yêu thương này lưu lại ${items.length} khoảnh khắc dịu dàng của hai bạn.',
