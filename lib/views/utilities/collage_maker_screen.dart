  List<_EditableCollagePhoto> _syncEditablePhotos(List<String> urls) {
    final existingBySource = <String, List<_EditableCollagePhoto>>{};
    for (final item in _editablePhotos) {
      existingBySource.putIfAbsent(item.source, () => []).add(item);
    }

    _editablePhotos
      ..clear()
      ..addAll(urls.map((url) {
        final existing = existingBySource[url];
        if (existing != null && existing.isNotEmpty) {
          return existing.removeAt(0);
        }
        return _EditableCollagePhoto(source: url);
      }));

    if (_activeEditorIndex != null &&
        _activeEditorIndex! >= _editablePhotos.length) {
      _activeEditorIndex = null;
    }
    return _editablePhotos;
  }

