  void _onMemoryLibraryChanged() {
    if (!mounted) return;
    final uid = FirebaseAuth.instance.currentUser?.uid;
    if (uid != _memoryOwnerUid || widget.houseId != _memoryOwnerHouse) {
      _memoryOwnerUid = uid;
      _memoryOwnerHouse = widget.houseId;
      _selectedMemoryPhotoKeys.clear();
      _hasSuggestedMemorySelection = false;
      _editablePhotos.clear();
      _privateMediaUrlService.clear();
    }
    _applyMemoryPhotos(_memoryLibrary.photos);
    setState(() {
      _isMemoryLoading = _memoryLibrary.loading;
      _hasMemoryLoadError = _memoryLibrary.hasError;
    });
    if (!_memoryLibrary.loading && _memoryLibrary.photos.isNotEmpty) {
      unawaited(_hydrateCollagePrivatePhotos(_memoryLibrary.photos));
    }
  }

  void _toggleMemoryPhoto(Map<String, dynamic> item) {
    final key = _memoryPhotoKey(item);
    if (key.isEmpty) return;
    final maxPhotos = _maxPhotosForCurrentStyle();
    setState(() {
      _hasSuggestedMemorySelection = true;
      if (_selectedMemoryPhotoKeys.contains(key)) {
        _selectedMemoryPhotoKeys.remove(key);
      } else if (_selectedMemoryPhotoKeys.length < maxPhotos) {
        _selectedMemoryPhotoKeys.add(key);
      }
      _markCollagePreviewDirty();
    });
    _scheduleAutoGenerate(immediate: true);
  }

  Future<void> _hydrateCollagePrivatePhotos(
    List<Map<String, dynamic>> items,
  ) async {
    final generation = ++_privateHydrationGeneration;
    final houseId = widget.houseId.trim();
    if (houseId.isEmpty) return;
    await _hydratePrivateMemoryUrls(items, houseId);
    if (!mounted || generation != _privateHydrationGeneration) return;
    _applyMemoryPhotos(items);
  }

