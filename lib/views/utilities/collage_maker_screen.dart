  void _applyMemoryPhotos(List<Map<String, dynamic>> photos) {
    final normalizedPhotos = <Map<String, dynamic>>[];
    for (final item in photos) {
      final normalized = _normalizePhotoItem(item);
      if (normalized != null) normalizedPhotos.add(normalized);
    }
    final sorted = CollageMemoryPhotos.catalog(normalizedPhotos);
    final months = <String>{};
    for (final item in sorted) {
      final ts = item['ts'] as int? ?? 0;
      if (ts > 0) {
        final date = DateTime.fromMillisecondsSinceEpoch(ts);
        months.add('${date.year}-${date.month.toString().padLeft(2, '0')}');
      }
    }
    final existingKeys = sorted
        .map(_memoryPhotoKey)
        .where((e) => e.isNotEmpty)
        .toSet();
    _hiddenMemoryPhotoKeys.removeWhere((key) => !existingKeys.contains(key));
    if (!mounted) return;
    setState(() {
      _memoryPhotos = sorted;
      _selectedMemoryPhotoKeys.removeWhere(
        (key) => !existingKeys.contains(key),
      );
      if (!_hasSuggestedMemorySelection && sorted.isNotEmpty) {
        _hasSuggestedMemorySelection = true;
        _selectedMemoryPhotoKeys.addAll(sorted.take(4).map(_memoryPhotoKey));
      }
      _availableMonths = months.toList()..sort((a, b) => b.compareTo(a));
      _hasMemoryLoadError = false;
      _markCollagePreviewDirty();
      if (_selectedMonth != 'all' &&
          !_availableMonths.contains(_selectedMonth)) {
        _selectedMonth = 'all';
      }
    });
    _scheduleAutoGenerate(immediate: true);
  }

