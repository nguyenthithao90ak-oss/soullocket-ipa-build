  List<_EditableCollagePhoto> _syncEditablePhotos(List<String> urls) {
    final stableKeyBySource = <String, String>{};
    if (_isFromMemory) {
      for (final item in _getFilteredMemoryItems()) {
        final source = _photoCollageUrl(item);
        if (source.isNotEmpty) {
          stableKeyBySource[source] = _memoryPhotoKey(item);
        }
      }
    }
    final retained = <_EditableCollagePhoto>[];
    for (final item in _editablePhotos) {
      final stableKey = stableKeyBySource[item.source] ?? item.stableKey;
      final stillPresent = urls.any(
        (url) => url == item.source || stableKeyBySource[url] == stableKey,
      );
      if (stillPresent) retained.add(item);
    }
    _editablePhotos
      ..clear()
      ..addAll(retained)
      ..addAll(
        urls
            .where((url) {
              final stableKey = stableKeyBySource[url];
              return !_editablePhotos.any(
                (item) =>
                    item.source == url ||
                    (stableKey != null && item.stableKey == stableKey),
              );
            })
            .map(
              (url) => _EditableCollagePhoto(
                source: url,
                stableKey: stableKeyBySource[url],
              ),
            ),
      );

    if (_activeEditorIndex != null &&
        _activeEditorIndex! >= _editablePhotos.length) {
      _activeEditorIndex = null;
    }
    return _editablePhotos;
  }

