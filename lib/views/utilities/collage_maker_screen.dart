  String _buildGenerationFingerprint(List<String> urls) {
    final normalizedStickers = _selectedStickers.toList()..sort();
    final transforms = _editablePhotos
        .map(
          (item) => [
            item.source,
            item.scale.toStringAsFixed(3),
            item.offset.dx.toStringAsFixed(3),
            item.offset.dy.toStringAsFixed(3),
          ].join('@'),
        )
        .join(';');
    return [
      _isFromMemory ? 'memory' : 'device',
      _selectedMonth,
      _selectedStyle,
      _selectedAspectRatio,
      _photoScale.toStringAsFixed(3),
      normalizedStickers.join(','),
      urls.length.toString(),
      Object.hashAll(urls).toString(),
      transforms,
    ].join('|');
  }

  int _nextCollageLayoutSeed() {
    final next = DateTime.now().microsecondsSinceEpoch & 0x7fffffff;
    return next == _collageLayoutSeed ? next + 1 : next;
  }

  void _scheduleAutoGenerate({bool immediate = false}) {
    _autoGenerateDebounceTimer?.cancel();
    final urls = _getFilteredUrls();
    if (urls.isEmpty) {
      _queuedAutoGenerationFingerprint = null;
      return;
    }

    _syncEditablePhotos(urls);
    final fingerprint = _buildGenerationFingerprint(urls);
    if (!_isGenerating &&
        fingerprint == _lastCompletedAutoGenerationFingerprint) {
      return;
    }

    _queuedAutoGenerationFingerprint = fingerprint;

    void trigger() {
      if (!mounted) return;
      if (_queuedAutoGenerationFingerprint != fingerprint) return;
      _generateCollage(
        triggeredAutomatically: true,
        expectedFingerprint: fingerprint,
        usePreviewQuality: true,
      );
    }

    if (immediate) {
      trigger();
    } else {
      _autoGenerateDebounceTimer =
          Timer(_autoGenerateDebounceDuration, trigger);
    }
  }

  String _decodedImageCacheKey(String sourceKey, int maxDimension) {
    return '$maxDimension::$sourceKey';
