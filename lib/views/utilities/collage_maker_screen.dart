  double _clampedEditorScale(double scale) => scale.clamp(1.0, 4.0).toDouble();

  Offset _clampedEditorOffset(Offset offset) {
    return Offset(
      offset.dx.clamp(-1.0, 1.0).toDouble(),
      offset.dy.clamp(-1.0, 1.0).toDouble(),
    );
  }

  void _selectEditablePhoto(int index) {
    if (index < 0 || index >= _editablePhotos.length) return;
    setState(() => _activeEditorIndex = index);
  }

  void _startFramePinch(int index, ScaleStartDetails details) {
    if (index < 0 || index >= _editablePhotos.length) return;
    final photo = _editablePhotos[index];
    _framePinchSession = _FramePinchSession(
      index: index,
      startOffset: photo.offset,
      startScale: photo.scale,
    );
    _selectEditablePhoto(index);
  }

  void _updateFramePinch(int index, ScaleUpdateDetails details) {
    final session = _framePinchSession;
    if (session == null ||
        session.index != index ||
        index >= _editablePhotos.length) {
      return;
    }
    final tileSize = _previewTileSize <= 0 ? 1.0 : _previewTileSize;
    setState(() {
      final photo = _editablePhotos[index];
      photo.scale = _clampedEditorScale(session.startScale * details.scale);
      final divisor = max(1.0, tileSize * 0.42 / photo.scale);
      photo.offset = _clampedEditorOffset(
        session.startOffset + details.focalPointDelta / divisor,
      );
      _markCollagePreviewDirty();
    });
    _scheduleAutoGenerate();
  }

  void _endFramePinch() {
    _framePinchSession = null;
  }

  void _resetEditablePhoto(int index) {
