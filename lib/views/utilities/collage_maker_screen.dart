      final date = dates.first;
      return CollageDecor.memory(
        occasionLabel: 'Kỷ niệm ngày ${_formatDateLabel(date)}',
        message:
            'Chúc ngày kỷ niệm này luôn lấp lánh, ấm áp và đầy những cái nắm tay thật lâu.',
      );
