  Future<ui.Image> _loadImage(
    dynamic source, {
    required int maxDimension,
  }) async {
    if (source is String && source.startsWith('http')) {
      final cacheKey = _decodedImageCacheKey(source, maxDimension);
      final cached = _decodedImageCache[cacheKey];
      if (cached != null) {
        return cached;
      }
      final image = await _loadCachedNetworkImage(
        source,
        maxDimension: maxDimension,
      );
      _cacheDecodedImage(cacheKey, image);
      return image;
    } else if (source is String) {
      final cacheKey = _decodedImageCacheKey(source, maxDimension);
      final cached = _decodedImageCache[cacheKey];
      if (cached != null) {
        return cached;
      }
      final bytes = await File(source).readAsBytes();
      final image = await _decodeImageBytes(
        bytes,
        maxDimension: maxDimension,
      );
      _cacheDecodedImage(cacheKey, image);
      return image;
    } else if (source is Uint8List) {
      return _decodeImageBytes(
        source,
        maxDimension: maxDimension,
      );
    } else {
      throw Exception('Unsupported image source');
    }
  }

  Future<ui.Image> _loadCachedNetworkImage(
    String url, {
    required int maxDimension,
  }) async {
    final provider = CachedNetworkImageProvider(
      url,
      maxWidth: maxDimension,
      maxHeight: maxDimension,
    );
    final stream = provider.resolve(const ImageConfiguration());
    final completer = Completer<ui.Image>();
    late ImageStreamListener listener;
    Timer? timeoutTimer;

    void cleanup() {
      timeoutTimer?.cancel();
      stream.removeListener(listener);
    }

    listener = ImageStreamListener(
      (imageInfo, _) {
        if (completer.isCompleted) return;
        cleanup();
        completer.complete(imageInfo.image);
      },
      onError: (error, stackTrace) {
        if (completer.isCompleted) return;
        cleanup();
        completer.completeError(error, stackTrace);
      },
    );

    timeoutTimer = Timer(const Duration(seconds: 18), () {
      if (completer.isCompleted) return;
      cleanup();
      completer.completeError(TimeoutException(L10nService().translate('util_tinhknimqu_ae5ec5')));
    });

    stream.addListener(listener);
    return completer.future;
  }

  Future<ui.Image> _decodeImageBytes(
    Uint8List bytes, {
    required int maxDimension,
  }) async {
    final codec = await ui.instantiateImageCodec(
      bytes,
      targetWidth: maxDimension,
      targetHeight: maxDimension,
      allowUpscaling: false,
    );
    final frame = await codec.getNextFrame();
    return frame.image;
  }

  Future<List<ui.Image>> _loadImagesForCollage(
    List<String> urls,
    int requestId,
    int maxDimension,
  ) async {
    final images = <ui.Image>[];
    for (var index = 0; index < urls.length; index += _imageLoadBatchSize) {
      if (requestId != _generationTicket) {
        break;
      }
      final batch = urls.skip(index).take(_imageLoadBatchSize).toList();
      final loaded = await Future.wait(
        batch.map((url) async {
          try {
            if (requestId != _generationTicket) {
              return null;
            }
            return await _loadImage(
              url,
              maxDimension: maxDimension,
            );
          } catch (e) {
            debugPrint(
              'Error loading image $url: ${AppErrorMapper.resolve(e).message}',
            );
            return null;
          }
        }),
      );
      images.addAll(loaded.whereType<ui.Image>());
      if (requestId != _generationTicket) {
        break;
      }
      await Future<void>.delayed(Duration.zero);
    }
    return images;
  }

  Future<void> _generateCollage({
    bool bypassDebounce = false,
    bool triggeredAutomatically = false,
    String? expectedFingerprint,
    bool usePreviewQuality = false,
    bool randomizeLayout = false,
  }) async {
    if (!bypassDebounce &&
        !triggeredAutomatically &&
        expectedFingerprint == null &&
        !usePreviewQuality) {
      _scheduleAutoGenerate();
      return;
    }

    final int requestId = ++_generationTicket;
    if (randomizeLayout) {
      _collageLayoutSeed = _nextCollageLayoutSeed();
    }
    final int layoutSeed = _collageLayoutSeed;
    _autoGenerateDebounceTimer?.cancel();
    var urls = _getFilteredUrls();
    final editablePhotos = _syncEditablePhotos(urls);
    urls = editablePhotos.map((item) => item.source).toList(growable: false);
    if (urls.isEmpty) {
      ScaffoldMessenger.of(context).showSnackBar(
        SnackBar(content: Text(L10nService().translate('util_chacnhghp_17d056'))),
      );
      return;
    }

    final fingerprint =
        expectedFingerprint ?? _buildGenerationFingerprint(urls);
    if (triggeredAutomatically &&
        !_isGenerating &&
        fingerprint == _lastCompletedAutoGenerationFingerprint) {
      return;
    }

    setState(() {
      _isGenerating = true;
    });

    try {
      // Limit to 50 photos randomly if too many from memory
      if (_isFromMemory && urls.length > 50) {
        urls = List<String>.from(urls)..shuffle(Random(layoutSeed ^ 0x19A7));
        urls = urls.take(50).toList();
      }

      final targetDecodeDimension = usePreviewQuality
          ? _collagePreviewDecodeMaxDimension
          : _collageDecodeMaxDimension;
      final uiImages = await _loadImagesForCollage(
        urls,
        requestId,
        targetDecodeDimension,
      );
      if (requestId != _generationTicket) {
        return;
      }
      if (uiImages.isEmpty) {
        throw Exception(L10nService().translate('util_khngticnhn_326853'));
      }

      final arrangedImages = uiImages;

      String title = _titleCtrl.text.trim();
      if (title.isEmpty) {
        title = _defaultCollageTitle();
      }

      final Uint8List? collageBytes = await CollageGenerator.generateCollage(
        arrangedImages,
        title,
        _selectedStyle,
        decor: _buildCollageDecor(),
        options: CollageRenderOptions(
          stickers: _selectedStickers.toList(),
          photoScale: _photoScale,
          outputAspectRatio: _activeAspectPreset.ratio,
          backgroundTheme: _selectedBackgroundTheme,
          layoutSeed: layoutSeed,
          renderQuality: usePreviewQuality
              ? CollageRenderQuality.preview
              : CollageRenderQuality.full,
          photoTransforms: editablePhotos
              .map((item) => item.transform)
              .toList(growable: false),
        ),
      );

      if (collageBytes != null && mounted && requestId == _generationTicket) {
        setState(() {
          _generatedCollageBytes = collageBytes;
          _hasFullQualityRender = !usePreviewQuality;
        });
        if (triggeredAutomatically) {
          _lastCompletedAutoGenerationFingerprint = fingerprint;
        }
      }
    } catch (e) {
      if (mounted && requestId == _generationTicket) {
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(
            content: Text(
              AppErrorMapper.resolve(
                e,
                fallbackMessage:
                    L10nService().translate('util_chathtocol_bc7661'),
              ).message,
            ),
          ),
        );
      }
    } finally {
      if (mounted && requestId == _generationTicket) {
        setState(() => _isGenerating = false);
      }
    }
  }

  Future<bool> _ensureFullQualityCollage() async {
    if (_generatedCollageBytes == null) {
      return false;
    }
    if (_hasFullQualityRender) {
      return true;
    }

    await _generateCollage(
      bypassDebounce: true,
      usePreviewQuality: false,
    );
    return _generatedCollageBytes != null && _hasFullQualityRender;
  }

  Future<void> _saveImage() async {
    if (_generatedCollageBytes == null) return;
    final canProceed = await CollageLimitService().checkLimitAndAskAd(context);
    if (!mounted || !canProceed) return;
    final hasFullQuality = await _ensureFullQualityCollage();
    if (!mounted || !hasFullQuality || _generatedCollageBytes == null) return;
    try {
      final String name =
          'soullocket_collage_${DateTime.now().millisecondsSinceEpoch}';
      final result = await VisionGallerySaver.saveImage(
        _generatedCollageBytes!,
        quality: 100,
        name: name,
      );

      final isSuccess = result['isSuccess'] == true ||
          (result['filePath']?.toString().isNotEmpty ?? false);

      if (mounted) {
        if (isSuccess) {
          await CollageLimitService().consumeLimit();
          ScaffoldMessenger.of(context).showSnackBar(
            SnackBar(
                content: Text(L10nService().translate('util_lunhthnhcn_feffae'))),
          );
        } else {
          final message = result['errorMessage']?.toString();
          throw Exception(
              message?.isNotEmpty == true ? message : L10nService().translate('util_likhilunh_39db09'));
        }
      }
    } catch (e) {
      if (mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(
            content: Text(
              AppErrorMapper.resolve(
                e,
                fallbackMessage:
                    L10nService().translate('util_chathlunhl_a80365'),
              ).message,
            ),
          ),
        );
      }
    }
  }

  Future<void> _shareImage() async {
